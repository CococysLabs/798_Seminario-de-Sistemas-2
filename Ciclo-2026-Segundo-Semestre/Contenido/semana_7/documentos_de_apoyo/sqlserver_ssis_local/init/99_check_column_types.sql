SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE (TABLE_SCHEMA = N'staging' AND TABLE_NAME = N'VentasRawExcel' AND COLUMN_NAME IN (N'ProductoID', N'ClienteID'))
   OR (TABLE_SCHEMA = N'dbo' AND TABLE_NAME = N'DimProducto' AND COLUMN_NAME = N'ProductoID')
   OR (TABLE_SCHEMA = N'dbo' AND TABLE_NAME = N'DimCliente' AND COLUMN_NAME = N'ClienteID')
ORDER BY TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME;
GO
